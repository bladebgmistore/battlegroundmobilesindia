/**
 * Idempotent bootstrap + repair for the DB2 inventory/catalogue tables.
 *
 * DB2 owns: categories, products, accounts, uc_packages, special_products,
 * pages, coupons, site_settings, feedbacks and the legacy `feedback` table.
 * Every DB2 route calls `ensureStoreTables()` before touching these tables so
 * a brand-new Neon database is provisioned automatically on first request.
 *
 * IMPORTANT — this is also the schema-reconciliation layer:
 * `CREATE TABLE IF NOT EXISTS` does nothing to an existing table. After a
 * database update/import, old tables can be missing newer columns (for
 * example `is_active`, `sort_order`, `features`) or carry NULL visibility
 * flags. When that happens the public query silently returns an empty
 * catalogue while the admin panel (which does not filter by those flags)
 * still lists every row. The statements below therefore:
 *
 *   1. create any missing tables (including the new `pages` table),
 *   2. add missing columns to existing tables (`ALTER TABLE ... IF NOT EXISTS`),
 *   3. backfill NULL flags/ordering/features from safe defaults,
 *   4. honour legacy `is_published` / `status` columns when present, and
 *   5. migrate legacy `accounts` + `special_products` rows into `products`,
 *      creating a category row for any orphaned product slug.
 *
 * Nothing is ever dropped or overwritten, and every statement is idempotent.
 * A brand-new database ends up with exactly the same shape.
 *
 * The canonical DDL also lives in `drizzle/db2/` (generated by drizzle-kit);
 * the one-off production repair script is `sql/007_catalog_sync_repair.sql`.
 */
type G = typeof globalThis & {
  __bgmiStoreTablesReady?: Promise<boolean>;
  __bgmiStoreTablesError?: string;
};

