-- ============================================================================
-- 008 — UC / ACCOUNT ORDER FLOWS + ADMIN PRESENCE (DB3)
--
-- Run against DATABASE_URL_DB3 after deploying this build:
--
--   psql "$DATABASE_URL_DB3" -f sql/008_order_otp_presence.sql
--
-- Fully idempotent. The application also applies every statement below
-- automatically on the first request (`ensureOrderColumns()` in
-- src/lib/order-columns.ts and `ensurePresenceTable()` in
-- src/lib/admin-presence.ts), so running this script is optional — it just
-- makes the change explicit and auditable for existing databases.
--
-- What it adds:
--   1. orders.transaction_ref        — UPI / bank UTR for UC & account orders.
--   2. orders.otp_request_status     — none | pending | approved | rejected.
--   3. orders.otp_requested_at       — when the buyer asked for a new OTP.
--   4. orders.otp_request_paid       — refundable verification fee received.
--   5. orders.otp_request_paid_at    — timestamp of that payment.
--   6. orders.otp_issued_at          — when the CURRENT 6-digit code was
--                                      generated by the server.
--   7. admin_presence                — live "staff is reading this chat"
--                                      heartbeat used to suppress Telegram
--                                      alerts for messages that are already
--                                      being read in real time.
--
-- Supported OTP lifecycle (codes are always generated server-side):
--   none ──confirm purchase──► approved (first code auto-generated)
--   none ──pay verification──► pending ──admin approves──► approved (new code)
--                                      └─admin rejects ──► rejected
-- ============================================================================

BEGIN;

-- ── 1-6. orders ─────────────────────────────────────────────────────────────
ALTER TABLE orders ADD COLUMN IF NOT EXISTS transaction_ref varchar(64);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS otp_request_status varchar(16) NOT NULL DEFAULT 'none';
ALTER TABLE orders ADD COLUMN IF NOT EXISTS otp_requested_at timestamptz;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS otp_request_paid boolean NOT NULL DEFAULT false;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS otp_request_paid_at timestamptz;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS otp_issued_at timestamptz;

-- Backfill the status column for rows created before this migration.
UPDATE orders SET otp_request_status = 'none' WHERE otp_request_status IS NULL;

-- UC + account desks filter by category — keep those reads fast.
CREATE INDEX IF NOT EXISTS orders_category_created_idx ON orders (category_slug, created_at DESC);
CREATE INDEX IF NOT EXISTS orders_otp_request_idx ON orders (otp_request_status)
  WHERE otp_request_status = 'pending';

-- ── 7. admin presence ───────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS admin_presence (
  email varchar(180) PRIMARY KEY,
  active_ticket_id uuid,
  last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_presence_seen_idx ON admin_presence (last_seen_at DESC);

COMMIT;
