"use client";

import { useCallback, useEffect, useMemo, useState } from "react";
import { FiCheckCircle, FiClock, FiEye, FiEyeOff, FiKey, FiLock, FiRefreshCw, FiSearch, FiShield, FiUser, FiX, FiZap } from "react-icons/fi";
import { formatINR } from "@/lib/store-data";

type AccountOrder = {
  id: string;
  orderCode: string;
  customerName: string;
  customerWhatsapp: string;
  productName: string;
  amount: number;
  status: string;
  accountLoginType?: string | null;
  accountEmail?: string | null;
  accountPassword?: string | null;
  otpCode?: string | null;
  otpRequestStatus?: string | null;
  otpRequestedAt?: string | null;
  otpRequestPaid?: boolean;
  otpRequestPaidAt?: string | null;
  otpIssuedAt?: string | null;
  verificationPaid?: boolean;
  verificationPaidAt?: string | null;
  verificationScreenshot?: string | null;
  paymentScreenshot?: string | null;
  paidAt?: string | null;
  createdAt: string;
};

const STATUS_STYLE: Record<string, string> = {
  awaiting_contact: "border-amber-200 bg-amber-50 text-amber-700",
  payment_review: "border-sky-200 bg-sky-50 text-sky-700",
  payment_confirmed: "border-violet-200 bg-violet-50 text-violet-700",
  delivered: "border-emerald-200 bg-emerald-50 text-emerald-700",
  cancelled: "border-red-200 bg-red-50 text-red-600",
};

const REQUEST_STYLE: Record<string, string> = {
  pending: "border-amber-200 bg-amber-50 text-amber-700",
  approved: "border-emerald-200 bg-emerald-50 text-emerald-700",
  rejected: "border-red-200 bg-red-50 text-red-600",
  none: "border-[#dbe2ec] bg-[#f8fafc] text-[#64748b]",
};

const label = (value: string) => value.replaceAll("_", " ").toUpperCase();

const isPaid = (order: AccountOrder) =>
  Boolean(order.paidAt || order.verificationPaid || order.otpRequestPaid || order.status === "payment_confirmed" || order.status === "delivered");

/**
 * Admin → Account Orders.
 *
 * Account-store purchases get a dedicated desk showing the credentials, the
 * CURRENT active 6-digit OTP, the OTP request status and the payment state.
 *
 * OTP codes are generated by the SERVER only: confirming a purchase issues the
 * first code automatically, and approving a "Get New OTP" request issues a
 * brand-new one. Staff never type an OTP.
 */
export default function AdminAccountOrdersPanel({
  onToast,
  onChanged,
}: {
  onToast?: (message: string) => void;
  onChanged?: () => void;
}) {
  const [rows, setRows] = useState<AccountOrder[]>([]);
  const [loading, setLoading] = useState(true);
  const [offline, setOffline] = useState(false);
  const [query, setQuery] = useState("");
  const [requestFilter, setRequestFilter] = useState("all");
  const [revealed, setRevealed] = useState<Record<string, boolean>>({});
  const [busyId, setBusyId] = useState<string | null>(null);
  const [editing, setEditing] = useState<AccountOrder | null>(null);
  const [form, setForm] = useState({ accountLoginType: "", accountEmail: "", accountPassword: "" });

  const load = useCallback(async () => {
    try {
      const res = await fetch("/api/admin/account-orders", { cache: "no-store", credentials: "same-origin" });
      const data = await res.json().catch(() => null);
      if (res.ok && data?.orders) {
        setRows(data.orders as AccountOrder[]);
        setOffline(Boolean(data.databaseOffline));
      }
    } catch {
      // next poll retries
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    const kick = setTimeout(() => void load(), 0);
    const timer = setInterval(() => void load(), 10000);
    return () => { clearTimeout(kick); clearInterval(timer); };
  }, [load]);

  const pendingCount = useMemo(
    () => rows.filter((row) => (row.otpRequestStatus ?? "none") === "pending").length,
    [rows],
  );

  const filtered = useMemo(() => {
    const needle = query.trim().toLowerCase();
    return rows.filter((row) => {
      const request = row.otpRequestStatus ?? "none";
      if (requestFilter !== "all" && request !== requestFilter) return false;
      if (!needle) return true;
      return [row.orderCode, row.customerName, row.customerWhatsapp, row.accountEmail, row.productName, row.otpCode]
        .filter(Boolean)
        .some((value) => String(value).toLowerCase().includes(needle));
    });
  }, [rows, query, requestFilter]);

  const runOtpAction = async (order: AccountOrder, action: "approve_otp" | "reject_otp" | "generate_otp") => {
    if (action === "reject_otp" && !confirm(`Reject the OTP request for ${order.orderCode}?`)) return;
    setBusyId(order.id);
    try {
      const res = await fetch("/api/admin/account-orders", {
        method: "PATCH",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ id: order.id, action }),
      });
      const data = await res.json().catch(() => null);
      if (!res.ok) {
        onToast?.(data?.error ?? "Could not update the OTP request.");
        return;
      }
      onToast?.(
        action === "reject_otp"
          ? `OTP request for ${order.orderCode} rejected.`
          : `New 6-digit OTP generated for ${order.orderCode}${data?.otpCode ? `: ${data.otpCode}` : ""}.`,
      );
      await load();
      onChanged?.();
    } catch {
      onToast?.("Network error while updating the OTP request.");
    } finally {
      setBusyId(null);
    }
  };

  const patchOrder = async (order: AccountOrder, payload: Record<string, unknown>, message: string) => {
    setBusyId(order.id);
    try {
      const res = await fetch("/api/orders", {
        method: "PATCH",
        credentials: "same-origin",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ id: order.id, ...payload }),
      });
      const data = await res.json().catch(() => null);
      if (!res.ok) {
        onToast?.(data?.error ?? "Could not update this order.");
        return;
      }
      onToast?.(message);
      await load();
      onChanged?.();
    } catch {
      onToast?.("Network error while updating the order.");
    } finally {
      setBusyId(null);
    }
  };

  const openEditor = (order: AccountOrder) => {
    setEditing(order);
    setForm({
      accountLoginType: order.accountLoginType ?? "FACEBOOK",
      accountEmail: order.accountEmail ?? "",
      accountPassword: order.accountPassword ?? "",
    });
  };

  const when = (value?: string | null) =>
    value ? new Date(value).toLocaleString("en-IN", { dateStyle: "medium", timeStyle: "short" }) : "—";

  return (
    <div className="space-y-5">
      <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
        {[
          { label: "Account orders", value: rows.length, copy: "All time" },
          { label: "OTP requests", value: pendingCount, copy: "Waiting for approval" },
          { label: "OTP active", value: rows.filter((row) => row.otpCode).length, copy: "Codes issued" },
          { label: "Payment confirmed", value: rows.filter(isPaid).length, copy: "Paid orders" },
        ].map((card) => (
          <article key={card.label} className="rounded-2xl border border-[#e5e8ef] bg-white p-5">
            <p className="text-xs font-bold text-[#64748b]">{card.label}</p>
            <p className="mt-3 text-2xl font-black tracking-[-.04em] text-[#0f172a]">{card.value}</p>
            <p className="mt-1 flex items-center gap-1.5 text-[9px] font-black tracking-[.11em] text-[#0f4c81]">
              <span className="h-1.5 w-1.5 rounded-full bg-[#0e9f6e]" /> {card.copy.toUpperCase()}
            </p>
          </article>
        ))}
      </div>

      <section className="overflow-hidden rounded-xl border border-[#e5e8ef] bg-white">
        <div className="flex flex-wrap items-center justify-between gap-3 border-b border-[#e5e8ef] p-5">
          <div>
            <h2 className="font-black text-[#0f172a]">Account Orders</h2>
            <p className="mt-1 text-xs text-[#64748b]">
              Credentials, active OTP, OTP request status and payment confirmation{offline ? " (demo store)" : ""}.
            </p>
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <div className="relative">
              <FiSearch className="pointer-events-none absolute left-3 top-1/2 -translate-y-1/2 text-[#94a3b8]" />
              <input
                value={query}
                onChange={(event) => setQuery(event.target.value)}
                placeholder="Search order, buyer, OTP…"
                className="admin-input !h-9 !w-56 !pl-9 text-xs"
              />
            </div>
            <select
              value={requestFilter}
              onChange={(event) => setRequestFilter(event.target.value)}
              className="admin-input !h-9 !w-44 text-[10px]"
            >
              <option value="all">ALL REQUESTS</option>
              <option value="pending">PENDING APPROVAL</option>
              <option value="approved">APPROVED</option>
              <option value="rejected">REJECTED</option>
              <option value="none">NO REQUEST</option>
            </select>
            <span className="rounded bg-[#f1f5fb] px-2 py-1 text-[10px] font-bold text-[#64748b]">{filtered.length} ORDERS</span>
            <button onClick={() => void load()} className="grid h-9 w-9 place-items-center rounded-lg border border-[#dbe2ec] text-[#64748b] transition hover:text-[#0f4c81]" title="Refresh">
              <FiRefreshCw className={loading ? "animate-spin" : ""} />
            </button>
          </div>
        </div>

        {filtered.length ? (
          <div className="divide-y divide-[#e5e8ef]">
            {filtered.map((order) => {
              const request = order.otpRequestStatus ?? "none";
              const showPassword = Boolean(revealed[order.id]);
              const busy = busyId === order.id;
              return (
                <article key={order.id} className="p-5">
                  <div className="flex flex-wrap items-start justify-between gap-3">
                    <div className="min-w-0">
                      <p className="font-mono text-xs font-black text-[#0f4c81]">{order.orderCode}</p>
                      <h3 className="mt-1 text-sm font-black text-[#0f172a]">{order.productName}</h3>
                      <div className="mt-2 flex flex-wrap gap-3 text-[11px] text-[#64748b]">
                        <span className="inline-flex items-center gap-1"><FiUser className="text-[#0f4c81]" /> {order.customerName}</span>
                        <span className="inline-flex items-center gap-1 font-mono">{order.customerWhatsapp}</span>
                        <span className="inline-flex items-center gap-1"><FiClock /> {when(order.createdAt)}</span>
                        <span className="font-black text-[#0f172a]">{formatINR(order.amount)}</span>
                      </div>
                    </div>
                    <div className="flex flex-wrap items-center gap-2">
                      <span className={`rounded-full border px-2.5 py-1 text-[9px] font-black ${STATUS_STYLE[order.status] ?? "border-[#dbe2ec] bg-[#f8fafc] text-[#64748b]"}`}>
                        {label(order.status)}
                      </span>
                      <span className={`rounded-full border px-2.5 py-1 text-[9px] font-black ${REQUEST_STYLE[request] ?? REQUEST_STYLE.none}`}>
                        OTP REQUEST: {label(request)}
                      </span>
                      <span className={`rounded-full border px-2.5 py-1 text-[9px] font-black ${isPaid(order) ? "border-emerald-200 bg-emerald-50 text-emerald-700" : "border-amber-200 bg-amber-50 text-amber-700"}`}>
                        {isPaid(order) ? "PAYMENT CONFIRMED" : "PAYMENT PENDING"}
                      </span>
                    </div>
                  </div>

                  <div className="mt-4 grid gap-3 lg:grid-cols-3">
                    {/* Credentials */}
                    <div className="rounded-xl border border-[#e5e8ef] bg-[#f8fafc] p-4">
                      <p className="flex items-center gap-1.5 text-[9px] font-black tracking-[.13em] text-[#0f4c81]"><FiKey /> ACCOUNT ID &amp; PASSWORD</p>
                      {order.accountEmail && order.accountPassword ? (
                        <dl className="mt-3 space-y-2 text-[11px]">
                          <div className="flex items-center justify-between gap-2">
                            <dt className="text-[#64748b]">Login type</dt>
                            <dd className="font-black text-[#0f172a]">{order.accountLoginType || "—"}</dd>
                          </div>
                          <div className="flex items-center justify-between gap-2">
                            <dt className="text-[#64748b]">Account ID</dt>
                            <dd className="truncate font-mono font-black text-[#0f172a]">{order.accountEmail}</dd>
                          </div>
                          <div className="flex items-center justify-between gap-2">
                            <dt className="text-[#64748b]">Password</dt>
                            <dd className="flex items-center gap-1.5 font-mono font-black text-[#0f172a]">
                              {showPassword ? order.accountPassword : "•".repeat(Math.min(order.accountPassword.length, 12))}
                              <button
                                onClick={() => setRevealed((current) => ({ ...current, [order.id]: !showPassword }))}
                                aria-label={showPassword ? "Hide password" : "Show password"}
                                className="text-[#94a3b8] transition hover:text-[#0f4c81]"
                              >
                                {showPassword ? <FiEyeOff /> : <FiEye />}
                              </button>
                            </dd>
                          </div>
                        </dl>
                      ) : (
                        <p className="mt-2 text-[11px] leading-5 text-[#94a3b8]">
                          No credentials saved yet. Add the account ID &amp; password to deliver this purchase.
                        </p>
                      )}
                      <button
                        onClick={() => openEditor(order)}
                        className="mt-3 inline-flex w-full items-center justify-center gap-1.5 rounded-lg border border-[#0f4c81]/30 px-3 py-2 text-[9px] font-black tracking-[.1em] text-[#0f4c81] transition hover:bg-[#0f4c81] hover:text-white"
                      >
                        <FiKey /> {order.accountEmail ? "EDIT CREDENTIALS" : "SET CREDENTIALS"}
                      </button>
                    </div>

                    {/* OTP */}
                    <div className="rounded-xl border border-[#d9e4f0] bg-[#f3f8fe] p-4">
                      <p className="flex items-center gap-1.5 text-[9px] font-black tracking-[.13em] text-[#0f4c81]"><FiShield /> CURRENT ACTIVE OTP</p>
                      {order.otpCode ? (
                        <>
                          <p className="mt-2 font-mono text-2xl font-black tracking-[.28em] text-[#0f172a]">{order.otpCode}</p>
                          <p className="mt-1 text-[10px] text-[#64748b]">Issued {when(order.otpIssuedAt)}</p>
                        </>
                      ) : (
                        <p className="mt-2 text-sm font-black text-[#94a3b8]">Not generated yet</p>
                      )}
                      <p className="mt-2 text-[10px] leading-4 text-[#64748b]">
                        Generated automatically by the server — never typed manually.
                      </p>
                      <div className="mt-3 flex flex-wrap gap-2">
                        <button
                          onClick={() => void runOtpAction(order, request === "pending" ? "approve_otp" : "generate_otp")}
                          disabled={busy}
                          className="inline-flex flex-1 items-center justify-center gap-1.5 rounded-lg bg-[#0f4c81] px-3 py-2 text-[9px] font-black tracking-[.1em] text-white transition hover:bg-[#0a3557] disabled:opacity-50"
                        >
                          <FiZap /> {request === "pending" ? "APPROVE REQUEST" : order.otpCode ? "NEW OTP" : "GENERATE OTP"}
                        </button>
                        {request === "pending" && (
                          <button
                            onClick={() => void runOtpAction(order, "reject_otp")}
                            disabled={busy}
                            className="rounded-lg border border-red-200 px-3 py-2 text-[9px] font-black text-red-600 transition hover:bg-red-600 hover:text-white disabled:opacity-50"
                          >
                            REJECT
                          </button>
                        )}
                      </div>
                      {request === "pending" && (
                        <p className="mt-2 rounded-lg bg-[#fdf9ec] px-2.5 py-1.5 text-[10px] font-bold text-[#8a6d00]">
                          Requested {when(order.otpRequestedAt)} · verification payment {order.otpRequestPaid ? "received" : "pending"}
                        </p>
                      )}
                    </div>

                    {/* Payment + delivery */}
                    <div className="rounded-xl border border-[#e5e8ef] bg-white p-4">
                      <p className="flex items-center gap-1.5 text-[9px] font-black tracking-[.13em] text-[#0f4c81]"><FiCheckCircle /> PAYMENT &amp; DELIVERY</p>
                      <dl className="mt-3 space-y-2 text-[11px]">
                        <div className="flex items-center justify-between gap-2">
                          <dt className="text-[#64748b]">Purchase payment</dt>
                          <dd className="font-black text-[#0f172a]">{order.paidAt ? when(order.paidAt) : "Not confirmed"}</dd>
                        </div>
                        <div className="flex items-center justify-between gap-2">
                          <dt className="text-[#64748b]">OTP fee</dt>
                          <dd className="font-black text-[#0f172a]">
                            {order.verificationPaid || order.otpRequestPaid ? when(order.verificationPaidAt ?? order.otpRequestPaidAt) : "Not paid"}
                          </dd>
                        </div>
                        <div className="flex items-center justify-between gap-2">
                          <dt className="text-[#64748b]">Order status</dt>
                          <dd className="font-black text-[#0f172a]">{label(order.status)}</dd>
                        </div>
                      </dl>
                      <div className="mt-3 grid gap-2">
                        {order.status !== "payment_confirmed" && order.status !== "delivered" && (
                          <button
                            onClick={() => void patchOrder(order, { status: "payment_confirmed" }, `Payment confirmed for ${order.orderCode}.`)}
                            disabled={busy}
                            className="inline-flex items-center justify-center gap-1.5 rounded-lg border border-[#7c3aed]/40 px-3 py-2 text-[9px] font-black tracking-[.1em] text-[#7c3aed] transition hover:bg-[#7c3aed] hover:text-white disabled:opacity-50"
                          >
                            <FiCheckCircle /> CONFIRM PAYMENT
                          </button>
                        )}
                        {order.status !== "delivered" && (
                          <button
                            onClick={() => void patchOrder(order, { status: "delivered" }, `${order.orderCode} marked delivered.`)}
                            disabled={busy}
                            className="inline-flex items-center justify-center gap-1.5 rounded-lg border border-[#0e9f6e]/40 px-3 py-2 text-[9px] font-black tracking-[.1em] text-[#0e9f6e] transition hover:bg-[#0e9f6e] hover:text-white disabled:opacity-50"
                          >
                            <FiZap /> MARK DELIVERED
                          </button>
                        )}
                      </div>
                      <p className="mt-2 flex items-center gap-1 text-[9px] font-bold text-[#94a3b8]">
                        <FiLock /> Confirming payment auto-generates the first OTP.
                      </p>
                    </div>
                  </div>
                </article>
              );
            })}
          </div>
        ) : (
          <div className="p-12 text-center">
            <span className="mx-auto grid h-14 w-14 place-items-center rounded-2xl bg-[#e0eefb] text-2xl text-[#0f4c81]"><FiKey /></span>
            <p className="mt-4 text-sm font-black text-[#0f172a]">
              {loading ? "Loading account orders…" : rows.length ? "No account orders match this filter." : "No account orders yet."}
            </p>
            <p className="mt-1 text-xs text-[#64748b]">Every gaming-account purchase creates a detailed entry here.</p>
          </div>
        )}
      </section>

      {/* Credentials editor */}
      {editing && (
        <div className="modal-overlay fixed inset-0 z-[90] grid place-items-center bg-black/60 p-4 backdrop-blur-sm" onClick={() => setEditing(null)}>
          <div onClick={(event) => event.stopPropagation()} className="modal-card w-full max-w-lg rounded-2xl border border-[#dbe2ec] bg-white p-6 shadow-[0_30px_80px_rgba(15,40,70,.3)]">
            <div className="flex items-start justify-between">
              <div>
                <p className="text-[10px] font-black tracking-[.14em] text-[#0f4c81]">ACCOUNT CREDENTIALS</p>
                <p className="mt-1 font-mono text-sm font-black text-[#0f172a]">{editing.orderCode}</p>
                <p className="mt-1 text-xs text-[#64748b]">{editing.productName}</p>
              </div>
              <button onClick={() => setEditing(null)} aria-label="Close" className="grid h-9 w-9 place-items-center rounded-lg border border-[#dbe2ec] text-[#64748b] transition hover:bg-[#f1f5fb] hover:text-[#0f172a]"><FiX /></button>
            </div>
            <p className="mt-4 rounded-lg border border-[#d9e4f0] bg-[#f3f8fe] px-3 py-2 text-[11px] leading-5 text-[#64748b]">
              Saved credentials are revealed to the buyer (with their auto-generated OTP) as soon as the order is payment-confirmed or delivered.
            </p>
            <div className="mt-5 grid gap-3">
              <label className="grid gap-2 text-[10px] font-black tracking-[.12em] text-[#64748b]">ACCOUNT LOGIN TYPE
                <input value={form.accountLoginType} onChange={(event) => setForm({ ...form, accountLoginType: event.target.value })} placeholder="FACEBOOK / GOOGLE / PLAYER ID" className="admin-input" />
              </label>
              <label className="grid gap-2 text-[10px] font-black tracking-[.12em] text-[#64748b]">ACCOUNT ID / MAIL
                <input value={form.accountEmail} onChange={(event) => setForm({ ...form, accountEmail: event.target.value })} placeholder="account id or email" className="admin-input" />
              </label>
              <label className="grid gap-2 text-[10px] font-black tracking-[.12em] text-[#64748b]">PASSWORD
                <input value={form.accountPassword} onChange={(event) => setForm({ ...form, accountPassword: event.target.value })} placeholder="account password" className="admin-input font-mono" />
              </label>
            </div>
            <div className="mt-5 flex flex-wrap gap-2">
              <button
                onClick={() => {
                  const order = editing;
                  setEditing(null);
                  void patchOrder(
                    order,
                    { ...form, status: order.status === "delivered" ? "delivered" : "payment_confirmed" },
                    `Credentials saved for ${order.orderCode}. OTP issued automatically.`,
                  );
                }}
                className="admin-primary flex-1"
              >
                <FiKey /> SAVE &amp; AUTO-GENERATE OTP
              </button>
              <button
                onClick={() => {
                  const order = editing;
                  setEditing(null);
                  void patchOrder(order, form, `Credentials saved for ${order.orderCode}.`);
                }}
                className="rounded-xl border border-[#dbe2ec] px-4 py-3 text-[10px] font-black text-[#64748b] transition hover:bg-[#f1f5fb] hover:text-[#0f172a]"
              >
                SAVE ONLY
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
