/**
 * NULL flags are the classic post-import failure: the public query filters
 * `is_active = true`, which never matches NULL, so the whole catalogue goes
 * blank even though the rows are present and the admin panel lists them.
 */
const BACKFILL_STATEMENTS = [
  `UPDATE categories SET is_active = true WHERE is_active IS NULL`,
  `UPDATE categories SET sort_order = 100 WHERE sort_order IS NULL`,
  `UPDATE categories SET name = initcap(replace(slug, '-', ' ')) WHERE name IS NULL OR btrim(name) = ''`,
  `UPDATE products SET is_active = true WHERE is_active IS NULL`,
  `UPDATE products SET sort_order = 0 WHERE sort_order IS NULL`,
  `UPDATE products SET features = '[]'::jsonb WHERE features IS NULL`,
  `UPDATE accounts SET is_active = true WHERE is_active IS NULL`,
  `UPDATE accounts SET features = '[]'::jsonb WHERE features IS NULL`,
  `UPDATE uc_packages SET is_active = true WHERE is_active IS NULL`,
  `UPDATE special_products SET is_active = true WHERE is_active IS NULL`,
  `UPDATE special_products SET features = '[]'::jsonb WHERE features IS NULL`,
  `UPDATE pages SET is_active = true WHERE is_active IS NULL`,
  `UPDATE pages SET show_in_nav = false WHERE show_in_nav IS NULL`,
  `UPDATE pages SET sort_order = 100 WHERE sort_order IS NULL`,
  `UPDATE coupons SET is_active = true WHERE is_active IS NULL`,
];

/**
 * If the database update introduced a publish column (`is_published`) or a
 * status workflow (`status = 'published' | 'draft'`), honour it for rows whose
 * `is_active` value was never set. We deliberately only fill NULLs so an
 * explicit admin disable is never overwritten on the next boot.
 */
const LEGACY_PUBLISH_SYNC = `
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'products' AND column_name = 'is_published'
  ) THEN
    EXECUTE 'UPDATE products SET is_active = is_published WHERE is_active IS NULL AND is_published IS NOT NULL';
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'products' AND column_name = 'status'
  ) THEN
    EXECUTE 'UPDATE products SET is_active = (lower(coalesce(status, '''')) IN (''published'', ''active'', ''live'')) WHERE is_active IS NULL';
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'categories' AND column_name = 'is_published'
  ) THEN
    EXECUTE 'UPDATE categories SET is_active = is_published WHERE is_active IS NULL AND is_published IS NOT NULL';
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'categories' AND column_name = 'status'
  ) THEN
    EXECUTE 'UPDATE categories SET is_active = (lower(coalesce(status, '''')) IN (''published'', ''active'', ''live'')) WHERE is_active IS NULL';
  END IF;
END $$;
`;

/**
 * Bring older inventory forward.
 *
 * The single-database version of the store kept account deals in `accounts`
 * and supercar/X-suit packages in `special_products`. After the move to the
 * unified `products` table those rows stayed behind, so valid, published
 * stock became invisible to every current API. The inserts below are
 * idempotent (matched on title within the target category) and only copy
 * active rows.
 */
const LEGACY_INVENTORY_MIGRATION = [
  `INSERT INTO categories (name, slug, description, sort_order, is_active)
   SELECT 'Premium Accounts', 'accounts', 'Find the high-tier BGMI account that matches your play style.', 10, true
   WHERE EXISTS (SELECT 1 FROM accounts)
     AND NOT EXISTS (
       SELECT 1 FROM categories
       WHERE regexp_replace(lower(slug), '[^a-z]', '', 'g') IN ('account', 'accounts', 'premiumaccount', 'premiumaccounts')
     )`,
  // UC packages are their own dataset. Without an `uc` category the public
  // API (correctly) hides them, which looks like "UC vanished" in the nav.
  `INSERT INTO categories (name, slug, description, sort_order, is_active)
   SELECT 'UC Purchase', 'uc', 'High-value UC packages for your next BGMI upgrade.', 20, true
   WHERE EXISTS (SELECT 1 FROM uc_packages)
     AND NOT EXISTS (
       SELECT 1 FROM categories
       WHERE regexp_replace(lower(slug), '[^a-z]', '', 'g') IN ('uc', 'ucs', 'ucpackage', 'ucpackages', 'ucpurchase')
     )`,
  `INSERT INTO categories (name, slug, description, sort_order, is_active)
   SELECT 'Super Cars', 'super-cars', 'Premium limited-edition supercars with specialised card packs.', 30, true
   WHERE EXISTS (SELECT 1 FROM special_products WHERE regexp_replace(lower(category), '[^a-z]', '', 'g') IN ('car', 'cars', 'supercar', 'supercars'))
     AND NOT EXISTS (
       SELECT 1 FROM categories
       WHERE regexp_replace(lower(slug), '[^a-z]', '', 'g') IN ('car', 'cars', 'supercar', 'supercars')
     )`,
  `INSERT INTO categories (name, slug, description, sort_order, is_active)
   SELECT 'X-Suits', 'x-suits', 'Legendary BGMI X-Suits with secure guided delivery.', 40, true
   WHERE EXISTS (SELECT 1 FROM special_products WHERE regexp_replace(lower(category), '[^a-z]', '', 'g') IN ('xsuit', 'xsuits', 'xsuite'))
     AND NOT EXISTS (
       SELECT 1 FROM categories
       WHERE regexp_replace(lower(slug), '[^a-z]', '', 'g') IN ('xsuit', 'xsuits', 'xsuite')
     )`,
  `INSERT INTO products (category_slug, title, price, image, features, badge, sort_order, is_active)
   SELECT 'accounts', a.title, a.price, a.image, coalesce(a.features, '[]'::jsonb), a.badge,
          (row_number() OVER (ORDER BY a.created_at))::int - 1, coalesce(a.is_active, true)
   FROM accounts a
   WHERE coalesce(a.is_active, true) = true
     AND NOT EXISTS (
       SELECT 1 FROM products p
       WHERE p.category_slug = 'accounts' AND lower(p.title) = lower(a.title)
     )`,
  `INSERT INTO products (category_slug, title, price, image, features, badge, sort_order, is_active)
   SELECT
     CASE WHEN regexp_replace(lower(s.category), '[^a-z]', '', 'g') IN ('xsuit', 'xsuits', 'xsuite') THEN 'x-suits' ELSE 'super-cars' END,
     s.title, s.price, s.image, coalesce(s.features, '[]'::jsonb), s.badge,
     coalesce(s.sort_order, 0), coalesce(s.is_active, true)
   FROM special_products s
   WHERE coalesce(s.is_active, true) = true
     AND NOT EXISTS (
       SELECT 1 FROM products p
       WHERE p.category_slug = CASE WHEN regexp_replace(lower(s.category), '[^a-z]', '', 'g') IN ('xsuit', 'xsuits', 'xsuite') THEN 'x-suits' ELSE 'super-cars' END
         AND lower(p.title) = lower(s.title)
     )`,
];

/**
 * Bring legacy product category keys onto the canonical slugs the storefront
 * uses. Only the four known families are rewritten, so custom categories are
 * never touched; this is what makes "Supercar"-era rows appear under
 * `/category/super-cars` without a manual data migration.
 */
const CATEGORY_SLUG_NORMALIZATION = [
  `UPDATE products SET category_slug = 'accounts'
   WHERE category_slug <> 'accounts'
     AND regexp_replace(lower(category_slug), '[^a-z]', '', 'g') IN ('account', 'accounts', 'premiumaccount', 'premiumaccounts')`,
  `UPDATE products SET category_slug = 'uc'
   WHERE category_slug <> 'uc'
     AND regexp_replace(lower(category_slug), '[^a-z]', '', 'g') IN ('uc', 'ucs', 'ucpackage', 'ucpackages', 'ucpurchase')`,
  `UPDATE products SET category_slug = 'super-cars'
   WHERE category_slug <> 'super-cars'
     AND regexp_replace(lower(category_slug), '[^a-z]', '', 'g') IN ('car', 'cars', 'supercar', 'supercars')`,
  `UPDATE products SET category_slug = 'x-suits'
   WHERE category_slug <> 'x-suits'
     AND regexp_replace(lower(category_slug), '[^a-z]', '', 'g') IN ('xsuit', 'xsuits', 'xsuite')`,
];

/**
 * Every published product must have a category row, otherwise `/api/store`
 * cannot surface it on any category page. Runs after slug normalisation so it
 * never recreates a category for a legacy spelling of an existing one.
 */
const ORPHAN_CATEGORY_REPAIR = [
  `INSERT INTO categories (name, slug, description, sort_order, is_active)
   SELECT initcap(replace(p.category_slug, '-', ' ')), p.category_slug,
          'Products published from the admin catalog.', 100, true
   FROM (SELECT DISTINCT category_slug FROM products WHERE category_slug IS NOT NULL AND btrim(category_slug) <> '') p
   WHERE NOT EXISTS (
     SELECT 1 FROM categories c
     WHERE c.slug = p.category_slug
       OR (p.category_slug = 'accounts' AND regexp_replace(lower(c.slug), '[^a-z]', '', 'g') IN ('account', 'accounts', 'premiumaccount', 'premiumaccounts'))
       OR (p.category_slug = 'uc' AND regexp_replace(lower(c.slug), '[^a-z]', '', 'g') IN ('uc', 'ucs', 'ucpackage', 'ucpackages', 'ucpurchase'))
       OR (p.category_slug = 'super-cars' AND regexp_replace(lower(c.slug), '[^a-z]', '', 'g') IN ('car', 'cars', 'supercar', 'supercars'))
       OR (p.category_slug = 'x-suits' AND regexp_replace(lower(c.slug), '[^a-z]', '', 'g') IN ('xsuit', 'xsuits', 'xsuite'))
   )`
];

/**
 * Created only after the ALTER phase: an old table may lack `sort_order` or
 * `status`, and creating an index on a missing column would abort the whole
 * repair before it could add that column.
 */
const INDEX_STATEMENTS = [
  `CREATE INDEX IF NOT EXISTS products_category_idx ON products (category_slug, sort_order)`,
  `CREATE INDEX IF NOT EXISTS products_active_idx ON products (is_active)`,
  `CREATE INDEX IF NOT EXISTS categories_active_idx ON categories (is_active, sort_order)`,
  `CREATE INDEX IF NOT EXISTS pages_active_order_idx ON pages (is_active, sort_order)`,
  `CREATE INDEX IF NOT EXISTS feedbacks_status_idx ON feedbacks (status)`,
  `CREATE INDEX IF NOT EXISTS feedbacks_created_at_idx ON feedbacks (created_at DESC)`,
];

async function runStatements(statements: string[]): Promise<void> {
  for (const statement of statements) {
    await db2.execute(sql.raw(statement));
  }
}

/**
 * Bump this whenever a repair step is added. It is stored in `site_settings`
 * so the heavy ALTER/backfill/migration pass runs once per database upgrade
 * instead of on every serverless cold start. Table creation stays outside the
 * gate, so a dropped/renamed table is always recreated.
 */
const CATALOG_SCHEMA_VERSION = "2026-10-catalog-sync-3";

async function schemaSyncAlreadyApplied(): Promise<boolean> {
  try {
    const result = await db2.execute<{ ok: number }>(sql`
      SELECT 1 AS ok
      FROM site_settings
      WHERE setting_key = 'catalog_schema_version'
        AND value = ${JSON.stringify(CATALOG_SCHEMA_VERSION)}::jsonb
      LIMIT 1
    `);
    return result.rows.length > 0;
  } catch {
    // `site_settings` may have an unexpected shape on a legacy database —
    // fall through to the full repair pass rather than skip it.
    return false;
  }
}

async function markSchemaSyncApplied(): Promise<void> {
  try {
    await db2.execute(sql`
      INSERT INTO site_settings (setting_key, value)
      VALUES ('catalog_schema_version', ${JSON.stringify(CATALOG_SCHEMA_VERSION)}::jsonb)
      ON CONFLICT (setting_key) DO UPDATE
        SET value = EXCLUDED.value, updated_at = now()
    `);
  } catch (error) {
    // The marker is an optimisation, not a requirement. If a legacy
    // `site_settings` shape rejects the write, the repair still succeeded and
    // simply re-runs (idempotently) on the next boot.
    if (process.env.NODE_ENV !== "production") {
      console.warn("[store-tables] could not record the schema sync version:", error);
    }
  }
}

export function ensureStoreTables(): Promise<boolean> {
  const g = globalThis as G;
  if (g.__bgmiStoreTablesReady) return g.__bgmiStoreTablesReady;

  g.__bgmiStoreTablesReady = (async () => {
    try {
      // Always cheap and safe: provision anything that does not exist yet.
      await runStatements(CREATE_STATEMENTS);

      if (!(await schemaSyncAlreadyApplied())) {
        await runStatements(ALTER_STATEMENTS);
        // Legacy publish flags are consulted while is_active is still NULL.
        await db2.execute(sql.raw(LEGACY_PUBLISH_SYNC));
        // Remaining NULLs (no legacy flag) default to visible.
        await runStatements(BACKFILL_STATEMENTS);
        await runStatements(LEGACY_INVENTORY_MIGRATION);
        await runStatements(CATEGORY_SLUG_NORMALIZATION);
        await runStatements(ORPHAN_CATEGORY_REPAIR);
        await markSchemaSyncApplied();
      }

      // Idempotent and safe on every boot — recreates an index if it was
      // dropped, but never runs before the columns exist.
      await runStatements(INDEX_STATEMENTS);

      g.__bgmiStoreTablesError = undefined;
      return true;
    } catch (error) {
      // Database unreachable or insufficient privileges — retry on the next
      // request instead of caching the failure forever.
      g.__bgmiStoreTablesReady = undefined;
      g.__bgmiStoreTablesError = error instanceof Error ? error.message : String(error);
      if (process.env.NODE_ENV !== "production") {
        console.warn("[store-tables] schema sync failed:", g.__bgmiStoreTablesError);
      }
      return false;
    }
  })();

  return g.__bgmiStoreTablesReady;
}

/** Last schema-sync error, exposed by the admin health screen. */
export function getStoreTablesError(): string | undefined {
  return (globalThis as G).__bgmiStoreTablesError;
}
