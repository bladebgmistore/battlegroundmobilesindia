import { NextResponse, type NextRequest } from "next/server";
import { db3 } from "@/db";
import { orders } from "@/db/schema";
import { ensureOrderColumns } from "@/lib/order-columns";
import { demoGetOrderByCode, demoUpdateOrder, type DemoOrder } from "@/lib/demo-orders";
import { eq } from "drizzle-orm";

export const dynamic = "force-dynamic";

/**
 * Records the refundable verification / website-charge payment for a delivered
 * order — the OTP fee for account purchases, or the ₹499 website charge for
 * UC / X-Suit / Super-Car orders.
 *
 * ACCOUNT orders: paying here creates an OTP REQUEST on the same order
 * (`otp_request_status = "pending"`). The code itself is generated by the
 * server when an admin approves the request in the Account Orders desk — the
 * admin never has to type one, and no duplicate order row is created.
 *
 * POST { orderCode, screenshot? , markPaid? }
 */
const MAX_SCREENSHOT_CHARS = 2_900_000;

export async function POST(request: NextRequest) {
  try {
    const body = await request.json().catch(() => null);
    const orderCode = String(body?.orderCode ?? "").trim().slice(0, 24);
    const screenshot = typeof body?.screenshot === "string" ? body.screenshot : null;
    const markPaid = body?.markPaid === true;

    if (!orderCode) {
      return NextResponse.json({ error: "Missing order reference." }, { status: 400 });
    }
    if (!screenshot && !markPaid) {
      return NextResponse.json({ error: "Nothing to update." }, { status: 400 });
    }

    if (screenshot) {
      if (!/^data:image\/(png|jpe?g|webp);base64,/.test(screenshot)) {
        return NextResponse.json({ error: "Only PNG, JPG or WEBP screenshots are supported." }, { status: 400 });
      }
      if (screenshot.length > MAX_SCREENSHOT_CHARS) {
        return NextResponse.json({ error: "Screenshot is too large. Please upload a smaller image." }, { status: 400 });
      }
    }

    const now = new Date();
    const patch: Record<string, unknown> = {};
    if (screenshot) patch.verificationScreenshot = screenshot;
    if (markPaid) {
      patch.verificationPaid = true;
      patch.verificationPaidAt = now;
    }

    try {
      await ensureOrderColumns();
      const [existing] = await db3.select({
        id: orders.id,
        categorySlug: orders.categorySlug,
        otpRequestStatus: orders.otpRequestStatus,
      }).from(orders).where(eq(orders.orderCode, orderCode)).limit(1);

      if (!existing) {
        // Order row was never saved (DB was offline at checkout) — degrade
        // gracefully so the buyer flow is never interrupted.
        return NextResponse.json({ ok: true, saved: false, message: "Order not found; payment recorded locally." });
      }

      const isAccountOrder = existing.categorySlug === "accounts";
      if (markPaid && isAccountOrder) {
        // Queue the OTP request for admin approval (a fresh code is generated
        // automatically on approval).
        patch.otpRequestStatus = "pending";
        patch.otpRequestPaid = true;
        patch.otpRequestPaidAt = now;
        patch.otpRequestedAt = now;
      }

      await db3.update(orders).set(patch).where(eq(orders.id, existing.id));
      return NextResponse.json({ ok: true, saved: true, otpRequestStatus: isAccountOrder ? patch.otpRequestStatus ?? null : null });
    } catch {
      // Database offline — record on the demo order so the preview still works.
      const target = demoGetOrderByCode(orderCode);
      const demoPatch: Partial<DemoOrder> = {};
      if (screenshot) demoPatch.verificationScreenshot = screenshot;
      if (markPaid) {
        demoPatch.verificationPaid = true;
        demoPatch.verificationPaidAt = now;
        if (target?.categorySlug === "accounts") {
          demoPatch.otpRequestStatus = "pending";
          demoPatch.otpRequestPaid = true;
          demoPatch.otpRequestPaidAt = now;
          demoPatch.otpRequestedAt = now;
        }
      }
      const existing = demoUpdateOrder(orderCode, demoPatch);
      return NextResponse.json({ ok: true, saved: true, demo: true, otpRequestStatus: existing?.otpRequestStatus ?? null });
    }
  } catch {
    return NextResponse.json({ error: "Could not process payment confirmation." }, { status: 500 });
  }
}
